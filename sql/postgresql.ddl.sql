                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         scene VARCHAR(50) NOT NULL,
                                         file_name VARCHAR(255) NOT NULL,
                                         file_path VARCHAR(512) NOT NULL,
                                         file_size BIGINT NOT NULL,
                                         mime_type VARCHAR(128) NOT NULL,
                                         status VARCHAR(32) DEFAULT 'ENABLED',
                                         user_id BIGINT,
                                         company_id BIGINT,
                                         description TEXT,
                                         create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         deleted INTEGER DEFAULT 0,
                                         CONSTRAINT fk_ragfile_user FOREIGN KEY (user_id) REFERENCES users(id),
                                         CONSTRAINT fk_ragfile_company FOREIGN KEY (company_id) REFERENCES company(id)
);
CREATE INDEX idx_ragfile_scene ON rag_files(scene);
CREATE INDEX idx_ragfile_user_id ON rag_files(user_id);
CREATE INDEX idx_ragfile_company_id ON rag_files(company_id);
CREATE INDEX idx_ragfile_status ON rag_files(status);
