-- 用户表
CREATE TABLE IF NOT EXISTS users (
                                     id BIGINT PRIMARY KEY,
                                     username VARCHAR(64) UNIQUE NOT NULL,
                                     password VARCHAR(255) NOT NULL,
                                     email VARCHAR(128),
                                     phone VARCHAR(32),
                                     create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                     update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                     deleted INTEGER DEFAULT 0,
                                     roles VARCHAR(255) NOT NULL,
                                     company_id BIGINT
);
CREATE INDEX idx_user_username ON users(username);
CREATE INDEX idx_user_email ON users(email);
CREATE INDEX idx_user_phone ON users(phone);
CREATE INDEX idx_user_create_time ON users(create_time);
CREATE INDEX idx_user_update_time ON users(update_time);
CREATE INDEX idx_user_deleted ON users(deleted);
CREATE INDEX idx_user_company_id ON users(company_id);

-- 企业表
CREATE TABLE IF NOT EXISTS company (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       name VARCHAR(128) NOT NULL,
                                       description TEXT,
                                       auto_approve BOOLEAN DEFAULT FALSE,
                                       user_name VARCHAR(100) UNIQUE,
                                       password VARCHAR(255) NOT NULL,
                                       over_amount_must_audit decimal(18, 2) DEFAULT 0.0 NOT NULL,
                                       create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                       update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                       deleted INTEGER DEFAULT 0
);
CREATE INDEX idx_company_name ON company(name);
CREATE INDEX idx_company_user_name ON company(user_name);
CREATE INDEX idx_company_create_time ON company(create_time);
CREATE INDEX idx_company_update_time ON company(update_time);

-- 部门表（树形结构）
CREATE TABLE IF NOT EXISTS departments (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           parent_id BIGINT DEFAULT 0,
                                           company_id BIGINT NOT NULL,
                                           name VARCHAR(128) NOT NULL,
                                           description TEXT,
                                           create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                           update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                           deleted INTEGER DEFAULT 0,
                                           CONSTRAINT fk_dept_parent FOREIGN KEY (parent_id) REFERENCES departments(id),
                                           CONSTRAINT fk_dept_company FOREIGN KEY (company_id) REFERENCES company(id)
);
CREATE INDEX idx_dept_company_id ON departments(company_id);
CREATE INDEX idx_dept_parent_id ON departments(parent_id);
CREATE INDEX idx_dept_name ON departments(name);
CREATE INDEX idx_dept_create_time ON departments(create_time);
CREATE INDEX idx_dept_update_time ON departments(update_time);

-- 员工表
CREATE TABLE IF NOT EXISTS employees (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name VARCHAR(100),
                                         company_id BIGINT NOT NULL,
                                         department_id BIGINT,
                                         user_id BIGINT UNIQUE NOT NULL,
                                         position VARCHAR(64),
                                         employee_no VARCHAR(64),
                                         entry_date DATE,
                                         is_primary BOOLEAN DEFAULT TRUE,
                                         create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         deleted INTEGER DEFAULT 0,
                                         CONSTRAINT fk_emp_company FOREIGN KEY (company_id) REFERENCES company(id),
                                         CONSTRAINT fk_emp_dept FOREIGN KEY (department_id) REFERENCES departments(id),
                                         CONSTRAINT fk_emp_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_employee_name ON employees(name);
CREATE INDEX idx_employee_user_id ON employees(user_id);
CREATE INDEX idx_employee_company_id ON employees(company_id);
CREATE INDEX idx_employee_dept_id ON employees(department_id);
CREATE INDEX idx_employee_employee_no ON employees(employee_no);
CREATE INDEX idx_employee_create_time ON employees(create_time);
CREATE INDEX idx_employee_update_time ON employees(update_time);


-- 审批记录表
CREATE TABLE IF NOT EXISTS approvals (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         order_no VARCHAR(64) UNIQUE NOT NULL,
                                         company_id BIGINT NOT NULL,
                                         applicant_id BIGINT,
                                         approver_id BIGINT,
                                         status VARCHAR(32),
                                         trip_items JSONB DEFAULT '[]',
                                         reason VARCHAR(500),
                                         remark TEXT,
                                         create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         deleted INTEGER DEFAULT 0,
                                         CONSTRAINT fk_approval_company FOREIGN KEY (company_id) REFERENCES company(id),
                                         CONSTRAINT fk_approval_applicant_ename FOREIGN KEY (applicant_id) REFERENCES employees(id),
                                         CONSTRAINT fk_approval_approver_ename FOREIGN KEY (approver_id) REFERENCES employees(id)
);
CREATE INDEX idx_approval_order_no ON approvals(order_no);
CREATE INDEX idx_approval_company_id ON approvals(company_id);
CREATE INDEX idx_approval_applicant_id ON approvals(applicant_id);
CREATE INDEX idx_approval_approver_id ON approvals(approver_id);
CREATE INDEX idx_approval_status ON approvals(status);
CREATE INDEX idx_approval_create_time ON approvals(create_time);
CREATE INDEX idx_approval_update_time ON approvals(update_time);

-- 订单主表
CREATE TABLE IF NOT EXISTS orders (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      company_id BIGINT NOT NULL,
                                      order_no VARCHAR(64) UNIQUE NOT NULL,
                                      user_id BIGINT NOT NULL,
                                      username VARCHAR(64),
                                      order_type VARCHAR(32) NOT NULL,
                                      amount DECIMAL(12,2) NOT NULL,
                                      status VARCHAR(32) DEFAULT 'PENDING_PAYMENT',
                                      audit_status VARCHAR(32) DEFAULT 'PENDING',
                                      pay_time TIMESTAMP,
                                      pay_type VARCHAR(32),
                                      refundable BOOLEAN DEFAULT TRUE,
                                      refund_amount DECIMAL(12,2) DEFAULT 0,
                                      journey JSONB,
                                      create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                      update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                      deleted INTEGER DEFAULT 0,
                                      approval_id BIGINT NOT NULL,
                                      order_requirements TEXT DEFAULT NULL,
                                      remark VARCHAR(255),
                                      CONSTRAINT fk_order_company FOREIGN KEY (company_id) REFERENCES company(id),
                                      CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users(id),
                                      CONSTRAINT fk_order_approval FOREIGN KEY (approval_id) REFERENCES approvals(id)
);
CREATE INDEX idx_order_user_id ON orders(user_id);
CREATE INDEX idx_order_company_id ON orders(company_id);
CREATE INDEX idx_order_status ON orders(status);
CREATE INDEX idx_order_audit_status ON orders(audit_status);
CREATE INDEX idx_order_type ON orders(order_type);
CREATE INDEX idx_order_no ON orders(order_no);
CREATE INDEX idx_order_approval_id ON orders(approval_id);
CREATE INDEX idx_order_create_time ON orders(create_time);
CREATE INDEX idx_order_update_time ON orders(update_time);

-- 行程段表（多段行程）
CREATE TABLE IF NOT EXISTS journeys (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        order_id BIGINT NOT NULL,
                                        company_id BIGINT NOT NULL,
                                        flight_no VARCHAR(32),
                                        train_no VARCHAR(32),
                                        hotel_name VARCHAR(128),
                                        car_no VARCHAR(32),
                                        departure VARCHAR(128),
                                        arrival VARCHAR(128),
                                        departure_time TIMESTAMP,
                                        arrival_time TIMESTAMP,
                                        tickets JSONB,
                                        create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                        update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                        deleted INTEGER DEFAULT 0,
                                        trip_type varchar(50) NOT NULL,
                                        airline VARCHAR(100),
                                        cabin_class VARCHAR(50),
                                        CONSTRAINT fk_journey_order FOREIGN KEY (order_id) REFERENCES orders(id),
                                        CONSTRAINT fk_journey_company FOREIGN KEY (company_id) REFERENCES company(id)
);
CREATE INDEX idx_journey_order_id ON journeys(order_id);
CREATE INDEX idx_journey_company_id ON journeys(company_id);
CREATE INDEX idx_journey_flight_no ON journeys(flight_no);
CREATE INDEX idx_journey_train_no ON journeys(train_no);
CREATE INDEX idx_journey_hotel_name ON journeys(hotel_name);
CREATE INDEX idx_journey_car_no ON journeys(car_no);
CREATE INDEX idx_journey_create_time ON journeys(create_time);
CREATE INDEX idx_journey_update_time ON journeys(update_time);
CREATE INDEX idx_journey_trip_type ON journeys(trip_type);

-- 乘客表（常用乘客）
CREATE TABLE IF NOT EXISTS passengers (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          name VARCHAR(64) NOT NULL,
                                          gender VARCHAR(8),
                                          birthday VARCHAR(20),
                                          phone VARCHAR(32),
                                          id_type VARCHAR(32),
                                          id_number VARCHAR(64),
                                          company_id BIGINT,
                                          user_id BIGINT,
                                          create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                          update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                          deleted INTEGER DEFAULT 0,
                                          CONSTRAINT fk_passenger_company FOREIGN KEY (company_id) REFERENCES company(id),
                                          CONSTRAINT fk_passenger_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_passenger_user_id ON passengers(user_id);
CREATE INDEX idx_passenger_id_type ON passengers(id_type);
CREATE INDEX idx_passenger_id_number ON passengers(id_number);
CREATE INDEX idx_passenger_phone ON passengers(phone);
CREATE INDEX idx_passenger_company_id ON passengers(company_id);
CREATE INDEX idx_passenger_name ON passengers(name);
CREATE INDEX idx_passenger_create_time ON passengers(create_time);
CREATE INDEX idx_passenger_update_time ON passengers(update_time);

-- 票务明细表
CREATE TABLE IF NOT EXISTS tickets (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       journey_id BIGINT NOT NULL,
                                       card_no VARCHAR(64),
                                       travel_type VARCHAR(32),
                                       departure VARCHAR(128),
                                       arrival VARCHAR(128),
                                       departure_time TIMESTAMP,
                                       arrival_time TIMESTAMP,
                                       company_id BIGINT,
                                       passenger_id BIGINT,
                                       passenger_name VARCHAR(64),
                                       has_child BOOLEAN DEFAULT FALSE,
                                       child_age INTEGER,
                                       has_baby BOOLEAN DEFAULT FALSE,
                                       baby_age INTEGER,
                                       has_pet BOOLEAN DEFAULT FALSE,
                                       pet_type VARCHAR(32),
                                       amount DECIMAL(12,2),
                                       price DECIMAL(12,2),
                                       tax_fee DECIMAL(12,2),
                                       insurance_fee DECIMAL(12,2),
                                       create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                       update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                       deleted INTEGER DEFAULT 0,
                                       CONSTRAINT fk_ticket_journey FOREIGN KEY (journey_id) REFERENCES journeys(id),
                                       CONSTRAINT fk_ticket_company FOREIGN KEY (company_id) REFERENCES company(id),
                                       CONSTRAINT fk_ticket_passenger FOREIGN KEY (passenger_id) REFERENCES passengers(id)
);
CREATE INDEX idx_ticket_journey_id ON tickets(journey_id);
CREATE INDEX idx_ticket_company_id ON tickets(company_id);
CREATE INDEX idx_ticket_passenger_id ON tickets(passenger_id);
CREATE INDEX idx_ticket_card_no ON tickets(card_no);
CREATE INDEX idx_ticket_travel_type ON tickets(travel_type);
CREATE INDEX idx_ticket_create_time ON tickets(create_time);
CREATE INDEX idx_ticket_update_time ON tickets(update_time);


