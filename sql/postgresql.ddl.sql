-- 政策文档表（用于 RAG 矢量检索）
CREATE TABLE IF NOT EXISTS policy_documents (
                                                id          SERIAL PRIMARY KEY,
                                                company_id  BIGINT NOT NULL,
                                                dept_id     BIGINT,
                                                content     TEXT NOT NULL,
                                                embedding   VECTOR(1536),  -- text-embedding-v3 输出维度，需与 spring.ai.dashscope.embedding.options.dimensions 配置保持一致
                                                metadata    JSONB,
                                                scene       VARCHAR(50),
                                                enabled     BOOLEAN DEFAULT TRUE,
                                                create_time  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                                update_time  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                                CONSTRAINT fk_policy_company FOREIGN KEY (company_id) REFERENCES company(id),
                                                CONSTRAINT fk_policy_dept FOREIGN KEY (dept_id) REFERENCES departments(id)
);

-- 创建 HNSW 索引（用于向量相似度检索）
CREATE INDEX IF NOT EXISTS policy_documents_embedding_idx
    ON policy_documents USING hnsw (embedding vector_cosine_ops);

-- 创建公司和部门索引（加速隔离查询）
CREATE INDEX IF NOT EXISTS idx_policy_company_id ON policy_documents(company_id);
CREATE INDEX IF NOT EXISTS idx_policy_dept_id ON policy_documents(dept_id);
CREATE INDEX IF NOT EXISTS idx_policy_scene ON policy_documents(scene);
CREATE INDEX IF NOT EXISTS idx_policy_enabled ON policy_documents(enabled);
CREATE INDEX IF NOT EXISTS idx_policy_create_time ON policy_documents(create_time);
CREATE INDEX IF NOT EXISTS idx_policy_create_time ON policy_documents(update_time);

