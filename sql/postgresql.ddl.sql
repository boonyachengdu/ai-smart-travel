-- 1. 创建数据库（如果不存在）
-- ================================================
SELECT 'CREATE DATABASE smart_travel'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'smart_travel')\gexec

-- 连接数据库
\c smart_travel

-- ================================================
-- 2. 启用扩展（pgvector 用于向量存储）
-- ================================================
CREATE EXTENSION IF NOT EXISTS vector;

